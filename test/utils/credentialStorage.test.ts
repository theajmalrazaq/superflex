import { describe, expect, it, beforeEach, vi } from "vitest";
import {
  saveCredentials,
  getDecryptedCredentials,
  clearSavedCredentials,
  hasSavedCredentials,
  savePendingLogin,
  getPendingLogin,
  clearPendingLogin,
  getCredentialMetadata,
} from "../../src/utils/credentialStorage";

const storageMock = new Map();
vi.stubGlobal("chrome", {
  storage: {
    local: {
      get: (keys, cb) => {
        const res = {};
        for (const k of keys) {
          if (storageMock.has(k)) res[k] = storageMock.get(k);
        }
        cb(res);
      },
      set: (obj, cb) => {
        for (const [k, v] of Object.entries(obj)) {
          storageMock.set(k, v);
        }
        cb?.();
      },
      remove: (keys, cb) => {
        for (const k of keys) storageMock.delete(k);
        cb?.();
      },
    },
  },
});

const sessionStore = new Map();
globalThis.sessionStorage = {
  get length() {
    return sessionStore.size;
  },
  key: (index: number) => [...sessionStore.keys()][index] ?? null,
  getItem: (k) => sessionStore.get(k) || null,
  setItem: (k, v) => sessionStore.set(k, String(v)),
  removeItem: (k) => sessionStore.delete(k),
  clear: () => sessionStore.clear(),
};

describe("credentialStorage vault", () => {
  beforeEach(() => {
    storageMock.clear();
    sessionStore.clear();
  });

  it("encrypts and decrypts credentials accurately via AES-GCM", async () => {
    const username = "21K-1234";
    const password = "SuperSecretPassword#2026";
    const passphrase = "correct horse battery staple";

    const saved = await saveCredentials(username, password, passphrase);
    expect(saved).toBe(true);

    const has = await hasSavedCredentials();
    expect(has).toBe(true);

    const metadata = await getCredentialMetadata();
    expect(metadata).toMatchObject({
      hasCredentials: true,
      version: 3,
      rememberedOnDevice: true,
      maskedUsername: "21K***34",
    });

    const decrypted = await getDecryptedCredentials();
    expect(decrypted).not.toBeNull();
    expect(decrypted.username).toBe(username);
    expect(decrypted.password).toBe(password);
    expect(decrypted.maskedUsername).toBe("21K***34");
  });

  it("wipes credentials on clearSavedCredentials", async () => {
    await saveCredentials("21K-9999", "pass123", "vault-passphrase");
    expect(await hasSavedCredentials()).toBe(true);

    await clearSavedCredentials();
    expect(await hasSavedCredentials()).toBe(false);
    expect(await getDecryptedCredentials()).toBeNull();
  });

  it("requires a user passphrase of at least eight characters", async () => {
    expect(await saveCredentials("21K-1234", "pass123", "short")).toBe(false);
    expect(await hasSavedCredentials()).toBe(false);
  });

  it("automatically generates a secure random key when no passphrase is provided", async () => {
    const saved = await saveCredentials("21K-5678", "AutoGenerated#Secret");
    expect(saved).toBe(true);

    const decrypted = await getDecryptedCredentials();
    expect(decrypted).not.toBeNull();
    expect(decrypted.username).toBe("21K-5678");
    expect(decrypted.password).toBe("AutoGenerated#Secret");
  });

  it("handles pending login in sessionStorage across login redirect", () => {
    savePendingLogin("21K-5555", "secret");
    const pending = getPendingLogin();
    expect(pending).not.toBeNull();
    expect(pending.username).toBe("21K-5555");
    expect(pending.password).toBe("secret");

    clearPendingLogin();
    expect(getPendingLogin()).toBeNull();
  });
});

describe("credential schema boundaries", () => {
  it("rejects malformed and unsupported stored vault records", async () => {
    for (const record of [
      { iv: "value", ciphertext: 123 },
      { version: 999, iv: "aXY=", ciphertext: "Y2lwaGVy" },
    ]) {
      storageMock.set("superflex_encrypted_credentials", record);
      expect(await hasSavedCredentials()).toBe(false);
      expect(await getDecryptedCredentials()).toBeNull();
    }
  });

  it("rejects missing, expired and future pending-login timestamps", () => {
    for (const timestamp of [
      undefined,
      "yesterday",
      Date.now() - 6 * 60 * 1000,
      Date.now() + 60000,
    ]) {
      sessionStore.set(
        "superflex_pending_login",
        JSON.stringify({ username: "21K-1234", password: "password", timestamp }),
      );
      expect(getPendingLogin()).toBeNull();
      expect(sessionStore.has("superflex_pending_login")).toBe(false);
    }
  });
});
